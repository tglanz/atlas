"""Turns an export directory of the movements into seed migrations."""

from __future__ import annotations

import json
from pathlib import Path

MOVEMENTS_FILE = "V5__seed_movements.sql"
ILLUSTRATIONS_FILE = "V7__seed_illustrations.sql"
STAGE_POSITIONS_FILE = "V9__seed_illustration_stage_positions.sql"


class InvalidExportError(Exception):
    """The file is not an export made by the export-movements command."""


def load_export(directory: Path) -> list[dict]:
    """The movements of an export directory, in key order."""
    files = sorted(directory.glob("*.json"))
    if not files:
        raise InvalidExportError(f"{directory} has no movement files.")
    movements = []
    for path in files:
        try:
            movement = json.loads(path.read_text(encoding="utf-8"))
            for field in ("key", "name", "description", "items", "stages", "tags", "illustrations"):
                movement[field]
            movement["edges"]
            if movement["key"] != path.stem:
                raise ValueError(f"the key {movement['key']!r} does not match the file name")
        except (ValueError, KeyError, TypeError) as error:
            raise InvalidExportError(f"{path} is not a valid movement file: {error!r}") from error
        movements.append(movement)
    return movements


def _text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _insert(table: str, columns: list[str], rows: list[list[str]]) -> str:
    if not rows:
        return ""
    values = ",\n".join("    (" + ", ".join(row) + ")" for row in rows)
    return f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n{values};\n\n"


def render_movements(movements: list[dict]) -> str:
    movement_rows, item_rows, stage_rows, tag_rows, edge_rows = [], [], [], [], []
    for movement in movements:
        key = _text(movement["key"])
        movement_rows.append([key, _text(movement["name"]), _text(movement["description"])])
        for position, item in enumerate(movement["items"]):
            item_rows.append([key, str(position), _text(item["type"]), _text(item["content"])])
        for position, stage in enumerate(movement["stages"]):
            stage_rows.append(
                [key, str(position), _text(stage["name"]), _text(stage["description"])]
            )
        tag_rows += [[key, _text(tag)] for tag in sorted(movement["tags"])]
        edge_rows += [
            [_text(edge["source"]), _text(edge["target"]), _text(edge["type"])]
            for edge in movement["edges"]
        ]
    edge_rows.sort()
    return (
        "-- Movements with their items, stages, tags and relationships. Generated by\n"
        "-- atlas-utils make-seed from an export; relationship rows cover both directions.\n\n"
        + _insert("movement", ["movement_key", "name", "description"], movement_rows)
        + _insert("movement_item", ["movement_key", "position", "type", "content"], item_rows)
        + _insert("movement_stage", ["movement_key", "position", "name", "description"], stage_rows)
        + _insert("movement_tag", ["movement_key", "tag"], tag_rows)
        + _insert("movement_edge", ["source_key", "target_key", "edge_type"], edge_rows)
    ).rstrip("\n") + "\n"


def render_illustrations(movements: list[dict]) -> str | None:
    """None when no movement has an illustration."""
    rows = [
        [_text(movement["key"]), str(position), _text(url)]
        for movement in movements
        for position, url in enumerate(movement["illustrations"])
    ]
    if not rows:
        return None
    return (
        "-- The Illustrations of the movements. Generated by atlas-utils make-seed.\n\n"
        + _insert("movement_illustration", ["movement_key", "position", "image_url"], rows)
    ).rstrip("\n") + "\n"


def render_stage_positions(movements: list[dict]) -> str:
    lines = ["-- Illustration stage associations. Generated by atlas-utils make-seed.", ""]
    for movement in movements:
        positions = movement.get(
            "illustrationStagePositions", list(range(len(movement["illustrations"])))
        )
        if (
            not isinstance(positions, list)
            or len(positions) != len(movement["illustrations"])
            or any(type(p) is not int or p < 0 for p in positions)
            or len(set(positions)) != len(positions)
        ):
            raise InvalidExportError(f"Invalid illustration stage positions for {movement['key']}")
        for index, stage in enumerate(positions):
            lines.append(
                f"UPDATE movement_illustration SET stage_position = {stage} "
                f"WHERE movement_key = {_text(movement['key'])} AND position = {index};"
            )
    return "\n".join(lines) + "\n"


def make_seed(export_dir: Path, out_dir: Path) -> list[Path]:
    """Writes the seed migrations into out_dir and returns the files written.

    The illustrations file is only written when the export has illustrations.
    """
    movements = load_export(export_dir)
    illustrations = render_illustrations(movements)
    stage_positions = render_stage_positions(movements) if illustrations is not None else None
    written = [out_dir / MOVEMENTS_FILE]
    written[0].write_text(render_movements(movements), encoding="utf-8")
    if illustrations is not None:
        written.append(out_dir / ILLUSTRATIONS_FILE)
        written[1].write_text(illustrations, encoding="utf-8")
        written.append(out_dir / STAGE_POSITIONS_FILE)
        written[2].write_text(stage_positions, encoding="utf-8")
    return written
